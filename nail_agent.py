def print_welcome():
    """打印欢迎信息"""
    print("=" * 60)
    print("       甲心助手 - 命令行版")
    print("=" * 60)
    print("输入你的问题，甲心助手来帮你分析。")
    print("输入 exit 或 quit 退出程序。")
    print("-" * 60)


def check_api_key() -> str:
    """检查 API Key 是否存在"""
    api_key = os.getenv("ANTHROPIC_API_KEY")
    if not api_key:
        print("\n❌ 错误：未找到 ANTHROPIC_API_KEY 环境变量。")
        print("\n请按照以下步骤设置：")
        print("  方法一（临时）：在终端输入")
        print("    export ANTHROPIC_API_KEY='你的API密钥'")
        print("\n  方法二（永久）：在 ~/.zshrc 或 ~/.bash_profile 中添加")
        print("    export ANTHROPIC_API_KEY='你的API密钥'")
        print("\n  API 密钥可在 https://console.anthropic.com 获取。")
        sys.exit(1)
    return api_key


def ask_xiaomei(client: anthropic.Anthropic, question: str):
    """调用 Claude API，流式输出回答"""
    print("\n甲心助手：", end="", flush=True)

    # 使用流式输出（streaming），让用户看到逐字生成的过程
    with client.messages.stream(
        model="claude-sonnet-4-6",   # 使用 claude-sonnet-4-6
        max_tokens=4000,              # 保证输出完整
        system=SYSTEM_PROMPT,
        messages=[
            {"role": "user", "content": question}
        ],
    ) as stream:
        # 逐块打印文字（流式输出）
        for text_chunk in stream.text_stream:
            print(text_chunk, end="", flush=True)

    print("\n")  # 回答结束后换行


def main():
    """主函数：启动甲心助手，循环等待用户输入"""
    # 1. 检查 API Key
    api_key = check_api_key()

    # 2. 初始化 Anthropic 客户端
    client = anthropic.Anthropic(api_key=api_key)

    # 3. 打印欢迎信息
    print_welcome()

    # 4. 主循环：等待用户输入，调用 API，输出回答
    while True:
        try:
            # 等待用户输入
            user_input = input("你：").strip()

            # 检查是否退出
            if user_input.lower() in ("exit", "quit", "退出"):
                print("\n甲心助手：好的，再见！有运营问题随时来找我。👋\n")
                break

            # 忽略空输入
            if not user_input:
                print("（请输入你的问题）")
                continue

            # 调用 API 并流式输出
            ask_xiaomei(client, user_input)

        except KeyboardInterrupt:
            # 用户按 Ctrl+C 时优雅退出
            print("\n\n甲心助手：好的，再见！👋\n")
            break
        except anthropic.AuthenticationError:
            print("\n❌ API Key 无效，请检查你的 ANTHROPIC_API_KEY。\n")
            break
        except anthropic.RateLimitError:
            print("\n⚠️  请求太频繁，请稍等一分钟再试。\n")
        except anthropic.APIConnectionError:
            print("\n⚠️  网络连接失败，请检查网络后重试。\n")
        except Exception as e:
            print(f"\n⚠️  出现错误：{e}\n")


if __name__ == "__main__":
    main()
